// Generates src/poker/preflopData.js: Monte Carlo all-in equity of each of the
// 169 starting hands against 1 and 3 random hands. Run with:  npm run gen:preflop
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { evaluate } from '../src/poker/evaluator.js';
import { CLASS_COMBOS, classLabel } from '../src/poker/handClasses.js';

function eqVsRandom(hole, opponents, iters) {
  const dead = new Set(hole);
  const deck = [];
  for (let c = 0; c < 52; c++) if (!dead.has(c)) deck.push(c);
  const n = deck.length;
  const k = 5 + 2 * opponents;
  let sum = 0;
  for (let it = 0; it < iters; it++) {
    for (let i = 0; i < k; i++) {
      const j = i + Math.floor(Math.random() * (n - i));
      const t = deck[i]; deck[i] = deck[j]; deck[j] = t;
    }
    const board = deck.slice(0, 5);
    const hs = evaluate([...hole, ...board]);
    let lost = false;
    let ties = 0;
    for (let o = 0; o < opponents; o++) {
      const os = evaluate([deck[5 + 2 * o], deck[6 + 2 * o], ...board]);
      if (os > hs) { lost = true; break; }
      if (os === hs) ties++;
    }
    if (!lost) sum += 1 / (ties + 1);
  }
  return sum / iters;
}

// Equity vs a hand drawn uniformly from a list of combos (a "calling range").
function eqVsRange(hole, rangeCombos, iters) {
  const dead = new Set(hole);
  const combos = rangeCombos.filter(([a, b]) => !dead.has(a) && !dead.has(b));
  let sum = 0;
  const used = new Uint8Array(52);
  for (let it = 0; it < iters; it++) {
    const [va, vb] = combos[Math.floor(Math.random() * combos.length)];
    used.fill(0);
    used[hole[0]] = used[hole[1]] = used[va] = used[vb] = 1;
    const board = [];
    while (board.length < 5) {
      const c = Math.floor(Math.random() * 52);
      if (!used[c]) { used[c] = 1; board.push(c); }
    }
    const hs = evaluate([...hole, ...board]);
    const vs = evaluate([va, vb, ...board]);
    sum += hs > vs ? 1 : hs === vs ? 0.5 : 0;
  }
  return sum / iters;
}

const EQ1 = [];
const EQ3 = [];
const t0 = Date.now();
for (let i = 0; i < 169; i++) {
  const hole = CLASS_COMBOS[i][0];
  EQ1.push(Number(eqVsRandom(hole, 1, 40000).toFixed(4)));
  EQ3.push(Number(eqVsRandom(hole, 3, 20000).toFixed(4)));
}

// Typical calling range vs a shove: the top 20% of hands by heads-up equity.
const byEq1 = Array.from({ length: 169 }, (_, i) => i).sort((a, b) => EQ1[b] - EQ1[a]);
const callCombos = [];
for (const i of byEq1) {
  if (callCombos.length >= 1326 * 0.2) break;
  callCombos.push(...CLASS_COMBOS[i]);
}
// EQC: equity when called. Fold equity is identical for every hand, so this is
// the right ordering for push/fold decisions (it values pairs and aces correctly).
const EQC = [];
for (let i = 0; i < 169; i++) EQC.push(Number(eqVsRange(CLASS_COMBOS[i][0], callCombos, 20000).toFixed(4)));

const fmt = (arr) => {
  const rows = [];
  for (let r = 0; r < 13; r++) rows.push('  ' + arr.slice(r * 13, r * 13 + 13).join(', ') + ',');
  return rows.join('\n');
};

const out = `// AUTO-GENERATED by scripts/gen-preflop.mjs — do not edit by hand.
// All-in equity of each starting-hand class (13x13 matrix order, row 0 = A)
// EQ1: vs one random hand, EQ3: vs three random hands,
// EQC: vs a typical calling range (top 20%) — used to rank push/fold hands.
// Order: ${Array.from({ length: 13 }, (_, i) => classLabel(i)).join(' ')} ...

export const EQ1 = [
${fmt(EQ1)}
];

export const EQ3 = [
${fmt(EQ3)}
];

export const EQC = [
${fmt(EQC)}
];
`;

const target = fileURLToPath(new URL('../src/poker/preflopData.js', import.meta.url));
writeFileSync(target, out);
console.log(`wrote ${target} in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
